#!/usr/bin/env bun
/**
 * The names of USDA's food categories, for the admin to show beside a food.
 *
 *   bun scripts/build-usda-categories.ts
 *   bun scripts/build-usda-categories.ts --from /path/to/data/usda
 *
 * usda.db keeps each food's category id but not the names, which live in the
 * FoodData Central downloads (data/usda, not in the repo). Two systems:
 * - SR Legacy and Foundation share one food_category.csv: ids 1–28, with a
 *   four-digit code ("0100" Dairy and Egg Products).
 * - Survey foods (FNDDS) use What We Eat in America's four-digit codes
 *   (wweia_food_category.csv: 1002 "Milk, whole").
 * The two id ranges never meet. Written to data/usda-categories.json, which is
 * small and committed, so every checkout has the names without the downloads.
 */

import { findTable, readCsv } from "../src/lib/usda-csv";
import type { UsdaCategory } from "../src/lib/usda-categories";

const from = process.argv.includes("--from") ? process.argv[process.argv.indexOf("--from") + 1]! : "data/usda";
const OUT = "data/usda-categories.json";

const byId = new Map<number, UsdaCategory>();

for (const dataset of ["foundation", "sr-legacy"]) {
  const path = await findTable(`${from}/${dataset}`, "food_category.csv");
  if (!path) throw new Error(`${dataset}: food_category.csv not found under ${from} — run scripts/fetch-usda.ts first`);
  for (const row of await readCsv(path)) {
    const id = Number(row.id);
    const next: UsdaCategory = { id, system: "fdc", code: row.code ?? "", description: row.description ?? "" };
    const seen = byId.get(id);
    // Both datasets ship the same table; if they ever disagree, say so rather than pick silently.
    if (seen && seen.description !== next.description) {
      console.warn(`category ${id}: "${seen.description}" (first seen) vs "${next.description}" in ${dataset}`);
    }
    if (!seen) byId.set(id, next);
  }
}

const wweiaPath = await findTable(`${from}/survey-fndds`, "wweia_food_category.csv");
if (!wweiaPath) throw new Error(`survey-fndds: wweia_food_category.csv not found under ${from}`);
for (const row of await readCsv(wweiaPath)) {
  const id = Number(row.wweia_food_category);
  byId.set(id, { id, system: "wweia", code: String(id), description: row.wweia_food_category_description ?? "" });
}

const categories = [...byId.values()].sort((a, b) => a.id - b.id);
await Bun.write(OUT, `${JSON.stringify({
  _comment: [
    "USDA food category names by id, from the FoodData Central downloads: food_category.csv (SR Legacy and",
    "Foundation, ids 1–28) and wweia_food_category.csv (survey foods, four-digit WWEIA codes).",
    "Generated by scripts/build-usda-categories.ts. Pluricook's own class for each is src/lib/anchor.ts.",
  ],
  categories,
}, null, 2)}\n`);

const fdc = categories.filter((c) => c.system === "fdc").length;
console.log(`${OUT}: ${categories.length} categories (${fdc} FDC, ${categories.length - fdc} WWEIA)`);
